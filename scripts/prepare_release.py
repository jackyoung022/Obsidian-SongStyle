#!/usr/bin/env python3
"""Build the standalone community theme and manual-install bundle using stdlib."""

import json
import re
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "宋韵·清和"
ICON_SNIPPET = ROOT / "snippets/宋韵图标.css"
BUNDLE_MARKER = "/* === Bundled Songyun icons: generated by scripts/prepare_release.py === */"


def main():
    manifest = json.loads((SOURCE / "manifest.json").read_text())
    version = manifest["version"]
    if not re.fullmatch(r"\d+\.\d+\.\d+", version):
        raise ValueError("Theme version must use x.y.z")

    base = (SOURCE / "theme.css").read_text().split(BUNDLE_MARKER, 1)[0].rstrip()
    icons = ICON_SNIPPET.read_text().strip()
    if ":where(body:not(.song-original-icons))" not in icons:
        raise ValueError("Icon selectors must support the original-icons toggle")
    css = base + "\n\n" + BUNDLE_MARKER + "\n\n" + icons + "\n"
    (SOURCE / "theme.css").write_text(css)
    (ROOT / "theme.css").write_text(css)

    store_manifest = dict(manifest, name="Songyun Qinghe")
    if not store_manifest.get("fundingUrl"):
        store_manifest.pop("fundingUrl", None)
    (ROOT / "manifest.json").write_text(
        json.dumps(store_manifest, indent=2, ensure_ascii=False) + "\n"
    )
    (SOURCE / "LICENSE").write_bytes((ROOT / "LICENSE").read_bytes())
    versions_path = ROOT / "versions.json"
    versions = json.loads(versions_path.read_text()) if versions_path.exists() else {}
    versions.setdefault("1.2.0", "1.6.0")
    versions[version] = manifest["minAppVersion"]
    versions_path.write_text(json.dumps(versions, indent=2) + "\n")

    note_names = {
        "宋韵主题预览.md": "light-preview.md",
        "宋韵深色主题预览.md": "dark-preview.md",
        "宋韵书卷展示.md": "scroll-block-preview.md",
    }

    def portable_readme(text):
        for old, new in note_names.items():
            text = text.replace(old, new)
        return text.replace("宋韵·清和/", "Songyun-Qinghe/").replace(
            "宋韵图标.css", "songyun-icons.css"
        )

    dist = ROOT / "dist"
    dist.mkdir(exist_ok=True)
    archive = dist / f"Obsidian-SongStyle-v{version}.zip"
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as z:
        for path in sorted(SOURCE.rglob("*")):
            if not path.is_file() or path.name.startswith("."):
                continue
            name = "Songyun-Qinghe/" + path.relative_to(SOURCE).as_posix()
            if path.suffix == ".md":
                z.writestr(name, portable_readme(path.read_text()))
            else:
                z.write(path, name)
        z.write(ICON_SNIPPET, "snippets/songyun-icons.css")
        for path in sorted((ROOT / "screenshots").glob("*.png")):
            z.write(path, "screenshots/" + path.name)
        for old, new in note_names.items():
            z.writestr("examples/" + new, portable_readme((ROOT / "examples" / old).read_text()))
        z.writestr("README.md", portable_readme((ROOT / "README.md").read_text()))
        z.write(ROOT / "LICENSE", "LICENSE")
        z.write(ROOT / "screenshot.png", "screenshot.png")

    with zipfile.ZipFile(archive) as z:
        if z.testzip():
            raise ValueError("ZIP validation failed")
        if z.read("Songyun-Qinghe/theme.css") != (ROOT / "theme.css").read_bytes():
            raise ValueError("Community and manual theme CSS differ")
    print(f"Built Songyun Qinghe {version}: {archive.name}")


if __name__ == "__main__":
    main()
